def get_base_stage(dex_id: int) -> int:
    # Traces back to the root base form of an evolutionary line
    curr = dex_id
    visited = {curr}
    while True:
        info = SPECIES_TABLE.get(curr)
        if not info or info.pre_evo is None or info.pre_evo in visited:
            return curr
        curr = info.pre_evo
        visited.add(curr)


def get_level_appropriate_species(dex_id: int, level: int) -> int:
    # Given a Pokémon species and encounter/trainer level, evolves it along its line
    curr = get_base_stage(dex_id)
    visited = {curr}
    while True:
        info = SPECIES_TABLE.get(curr)
        if not info or not info.evos:
            return curr
        # Check if any evolution condition is met at current level
        evolved = False
        for next_dex, req_level in info.evos:
            if level >= req_level and next_dex not in visited:
                curr = next_dex
                visited.add(curr)
                evolved = True
                break
        if not evolved:
            return curr


def get_3stage_starters() -> list[int]:
    # All base-stage Pokémon whose family has 3 stages
    starters: list[int] = []
    for dex, info in SPECIES_TABLE.items():
        if info.stage == 1 and info.pre_evo is None:
            has_stage_3 = False
            for mid_dex, _ in info.evos:
                mid_info = SPECIES_TABLE.get(mid_dex)
                if mid_info and len(mid_info.evos) > 0:
                    has_stage_3 = True
                    break
            if has_stage_3:
                starters.append(dex)
    return starters


def get_species_by_type(poke_type: str) -> list[int]:
    # All species IDs possessing the given type
    t_lower = poke_type.lower()
    return [
        dex for dex, info in SPECIES_TABLE.items()
        if t_lower in (info.types[0].lower(), info.types[1].lower())
    ]
